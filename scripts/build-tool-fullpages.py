def asset_version() -> int:
    """?v= for shared scripts. One home, CACHE_VERSION in sw.js — hard-coding
    it here is how tools.html once shipped explore.css?v=1 against a ?v=16
    homepage (the note in build-category-pages.js is the same incident)."""
    with open(SW_JS, encoding="utf-8") as fh:
        m = re.search(r"CACHE_VERSION\s*=\s*'v(\d+)-", fh.read())
    if not m:
        raise SystemExit("sw.js has no CACHE_VERSION = 'vN-<date>' — cannot version page assets")
    return int(m.group(1))


_TITLE_NOISE = re.compile(r"^[\s\W_]+", re.UNICODE)


def title_sort_key(title: str) -> str:
    """Byte-for-byte discovery_catalogue.title_sort_key: A–Z by title, emoji
    stripped, so previous/next follow the same order the category pages use."""
    stripped = _TITLE_NOISE.sub("", title or "")
    if not stripped:
        stripped = title or ""
    folded = unicodedata.normalize("NFKD", stripped)
    folded = "".join(ch for ch in folded if not unicodedata.combining(ch))
    return folded.casefold()


def slugify_category(name: str) -> str:
    """discovery_catalogue.slugify_category."""
    s = name.lower().replace("&", "and")
    s = re.sub(r"[^a-z0-9]+", "-", s)
    return s.strip("-")


def esc(text: str) -> str:
    return html.escape(str(text), quote=True)


def truncate(text: str, limit: int) -> str:
    text = re.sub(r"\s+", " ", str(text)).strip()
    if len(text) <= limit:
        return text
    cut = text[:limit].rsplit(" ", 1)[0].rstrip(",;:. ")
    return cut + "…"

# --------------------------------------------------------------------------
# Card fragment handling
# --------------------------------------------------------------------------
SCHEME_RE = re.compile(r"^[a-z][a-z0-9+.-]*:", re.I)
ATTR_RE = re.compile(r"""((?:href|src)\s*=\s*)(["'])((?:(?!\2).)*)\2""", re.S)
CARDS_LINK_RE = re.compile(r"^cards/([a-z0-9][a-z0-9\-]{0,79})\.html$")
SHELL_LINK_RE = re.compile(r"^tool\.html\?(?:card|t)=([a-z0-9][a-z0-9\-]{0,79})(?:$|&)")


def rewrite_asset(value: str) -> str:
    """A card is written for a root-level host (index.html / tool.html), so a
    bare relative link in its markup means 'from the site root'. From tool/ it
    would 404 one directory down — make it root-absolute. Values that already
    address themselves (scheme, protocol-relative, anchor, absolute) are
    left exactly as written."""
    v = value.strip()
    if not v or v.startswith(("#", "/", "//")) or SCHEME_RE.match(v):
        return value
    cards = CARDS_LINK_RE.match(v)
    if cards:
        return "/tool/" + cards.group(1) + ".html"
    shell = SHELL_LINK_RE.match(v)
    if shell:
        return "/tool/" + shell.group(1) + ".html"
    if " " in v:
        return value  # not a plain link; never guess
    return "/" + value


def split_scripts(fragment: str) -> list[tuple[str, bool]]:
    """(chunk, is_script) pieces: <script>…</script> (any attributes, incl.
    src) stays byte-for-byte untouched; only the markup between them is
    rewritten."""
    out: list[tuple[str, bool]] = []
    pos = 0
    for m in re.finditer(r"<script\b[^>]*>.*?</script>", fragment, re.S | re.I):
        if m.start() > pos:
            out.append((fragment[pos:m.start()], False))
        out.append((m.group(0), True))
        pos = m.end()
    if pos < len(fragment):
        out.append((fragment[pos:], False))
    return out or [("", False)]


def inline_fragment(fragment: str) -> str:
    return "".join(
        chunk if is_script else ATTR_RE.sub(
            lambda m: m.group(1) + m.group(2) + rewrite_asset(m.group(3)) + m.group(2),
            chunk,
        )
        for chunk, is_script in split_scripts(fragment)
    )

