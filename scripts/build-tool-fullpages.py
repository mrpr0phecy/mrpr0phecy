#!/usr/bin/env python3
"""build-tool-fullpages.py — render a full HTML page for EVERY tool in tool/.

    python3 scripts/build-tool-fullpages.py           # (re)write tool/*.html
    python3 scripts/build-tool-fullpages.py --check   # fail if any page has drifted

Why these pages exist
---------------------
Until 2026-10-05 the only way to RUN a tool was `tool.html?card=<slug>` — one
shared, long-lived document that swaps card fragments in and out. Two costs:

1. **Breakage.** Globals, listeners, timers and styles survive one card into
   the next (CONSTRAINTS.md "Card traps"), so the shell needs a whole check
   fleet to stay honest, and a card can still break the tool after it.
2. **Discovery.** A query-param URL is a JS shell to a crawler: non-JS readers
   (and every AI index) see an empty page.

`tool/<slug>.html` is the fix for the whole catalogue at once: a real URL, one
document per tool. The card fragment is the single implementation and is
INLINED verbatim — no fetch, no iframe, no JavaScript required for the tool to
work, and nothing from one tool can survive into another because there is no
"other" in the document.

What the page adds around the card:
- first-class navigation: breadcrumbs, previous/next tool in the category, a
  ranked related-tools grid (related.json, padded from the category) and the
  category hub — a tool is a page in a collection, not an island;
- the site search (a plain form, zero JS), the saved toolbox (toolbox.js +
  toolbox.css, the same panel as every list page) and the YMYL risk notice
  (risk-notices.js, the same call tool.html makes);
- crawlable head: static title/description from the fragment, canonical, OG,
  WebApplication + BreadcrumbList JSON-LD.

What it deliberately does NOT replace: `tool.html?card=` stays the stateful
shell — `&embed=1` (the documented embed contract), filled links
(`&<control>=<value>&run=1`) and multi-step jobs all carry URL state that a
static page cannot answer. Every filled-link surface (jobs.json, intents.json,
the share panel) keeps pointing at the shell.

Two rules, the same as build-tool-pages.py:
1. **Rendering must be deterministic** — the same inputs produce the same
   bytes, or --check is useless. No timestamps, no randomness; ordering comes
   from the catalogue (title sort, slug tie-break) exactly as the category
   pages order their rows.
2. **Published numbers are derived, never typed.** The tool count and the
   per-category counts come from cards.json at build time.

The card is inlined, but two things are rewritten:
- markup `href`/`src` values that resolve from the SITE ROOT are rewritten to
  root-absolute (`ai.html#x` -> `/ai.html#x`) so a link a card wrote for the
  root-injected shell still lands from one directory down. Scripts are never
  touched; only real markup attributes.
- a card's `cards/<slug>.html` link (raw fragment) becomes the full page.

Nothing here leaves the device: no analytics on these pages (they are the
catalogue, Product A), no third-party scripts, no cookies. The only runtime
requests are the card's own (offline by rule) plus toolbox.js's lazy
cards-lite.json lookup, which the list pages already make.
"""
