# --------------------------------------------------------------------------
# Context: ordering, previous/next, related
# --------------------------------------------------------------------------
def load_context(tools: list[dict]) -> dict:
    by_name = {t["name"]: t for t in tools}
    cat_tools: dict[str, list[dict]] = {}
    for t in tools:
        cat_tools.setdefault(t.get("category") or "General Tool", []).append(t)
    for cat in cat_tools:
        cat_tools[cat].sort(key=lambda t: (title_sort_key(t["title"]), t["name"]))

    prev_next: dict[str, tuple[str | None, str | None]] = {}
    for cat, group in cat_tools.items():
        n = len(group)
        for i, t in enumerate(group):
            if n == 1:
                prev_next[t["name"]] = (None, None)  # nothing to move to
            else:
                prev_next[t["name"]] = (group[i - 1]["name"], group[(i + 1) % n]["name"])

    try:
        with open(RELATED_JSON, encoding="utf-8") as fh:
            related_raw = json.load(fh)
    except (OSError, json.JSONDecodeError):
        related_raw = {}

    related: dict[str, list[str]] = {}
    for t in tools:
        slug = t["name"]
        cat = t.get("category") or "General Tool"
        ranked = related_raw.get(slug) or []
        picked = [s for s in ranked if s in by_name and s != slug][:8]
        if len(picked) < 8:
            skip = set(picked) | {slug, *prev_next.get(slug, (None, None))}
            for candidate in cat_tools.get(cat, []):
                if len(picked) >= 8:
                    break
                c = candidate["name"]
                if c in skip or c in picked:
                    continue
                picked.append(c)
        related[slug] = picked

    return {
        "count": len(tools),
        "version": asset_version(),
        "by_name": by_name,
        "cat_count": {c: len(g) for c, g in cat_tools.items()},
        "prev_next": prev_next,
        "related": related,
    }

# --------------------------------------------------------------------------
# Build / check
# --------------------------------------------------------------------------
def load_inputs() -> list[dict]:
    with open(CARDS_JSON, encoding="utf-8") as fh:
        tools = json.load(fh)
    if not isinstance(tools, list) or not tools:
        raise SystemExit("cards/cards.json is missing or empty — run: node generate-cards-json.js")
    return tools


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="fail when a rendered page differs from disk, a page is missing, or tool/ holds a page no tool declares")
    args = parser.parse_args()

    tools = load_inputs()
    ctx = load_context(tools)
    os.makedirs(OUT_DIR, exist_ok=True)

    drifted, written, missing = [], 0, []
    for tool in sorted(tools, key=lambda t: t["name"]):
        slug = tool["name"]
        frag_path = os.path.join(CARDS_DIR, slug + ".html")
        if not os.path.exists(frag_path):
            missing.append(slug)
            continue
        with open(frag_path, encoding="utf-8") as fh:
            fragment = fh.read()
        out = render_page(tool, fragment, ctx)
        target = os.path.join(OUT_DIR, slug + ".html")
        if args.check:
            if not os.path.exists(target):
                missing.append(slug)
            elif open(target, encoding="utf-8").read() != out:
                drifted.append(f"tool/{slug}.html")
        else:
            with open(target, "w", encoding="utf-8") as fh:
                fh.write(out)
            written += 1

    on_disk = {f[:-5] for f in os.listdir(OUT_DIR) if f.endswith(".html")}
    declared = {t["name"] for t in tools}
    orphans = sorted(on_disk - declared)

    if missing:
        print(f"  FAIL {len(missing)} tool page(s) missing a card fragment: {', '.join(missing[:8])}", file=sys.stderr)
        return 1
    if orphans:
        print(f"  FAIL tool/ page(s) with no tool in cards.json: {', '.join(orphans[:8])}", file=sys.stderr)
        print("       every file in tool/ is generated — delete orphans, they are not homes", file=sys.stderr)
        return 1
    if args.check:
        if drifted:
            print("tool/ full pages are stale — run: python3 scripts/build-tool-fullpages.py", file=sys.stderr)
            for path in drifted[:20]:
                print(f"  drift {path}", file=sys.stderr)
            return 1
        print(f"tool full pages OK — {len(tools)} page(s) match the cards")
        return 0

    total_kb = sum(os.path.getsize(os.path.join(OUT_DIR, t["name"] + ".html")) for t in tools)
    print(f"tool full pages: {written} written ({len(tools)} tools, {total_kb / 1048576:.1f} MB total) at tool/<slug>.html")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
