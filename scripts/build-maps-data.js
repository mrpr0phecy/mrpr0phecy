#!/usr/bin/env node
/**
 * build-maps-data.js — regenerate MostUsefulMaps' offline data files.
 *
 * MostUsefulMaps (maps.html) keeps working with no network at all: a vendored
 * world map, a vendored gazetteer and vendored country facts. Those three
 * files are *generated*, never hand-edited, and this is their generator:
 *
 *   maps/data/gazetteer.json   cities for offline search + nearest-place
 *   maps/data/countries.json   country facts for offline "what is here"
 *   maps/data/SOURCES.json     provenance: source package, version, hashes
 *
 * Sources are npm packages, pinned by version, unpacked outside the repository
 * (the repo is zero-dependency on purpose — AGENTS.md §2):
 *
 *   mkdir -p /tmp/maps-build && cd /tmp/maps-build
 *   npm pack all-the-cities@3.1.0 world-countries@5.1.0
 *   tar xzf all-the-cities-3.1.0.tgz && tar xzf world-countries-5.1.0.tgz
 *   npm i pbf@3                       # all-the-cities decodes a pbf file
 *
 *   node scripts/build-maps-data.js \
 *     --cities /tmp/maps-build/package/cities.pbf \
 *     --countries /tmp/maps-build/package/countries.json \
 *     --node-path /tmp/maps-build/node_modules
 *
 *   node scripts/build-maps-data.js --check     # verify what is committed
 *   node scripts/build-maps-data.js --provenance # refresh SOURCES.json from
 *                                               # the committed files (no
 *                                               # upstream packages needed)
 *
 * `--check` never needs the sources: it re-reads the shipped files and proves
 * they still match the hashes recorded in SOURCES.json. That is the drift
 * guard — it catches a hand-edit even though the upstream packages are not in
 * the repository and not in CI.
 *
 * Data provenance, both open:
 *   all-the-cities 3.1.0 (MIT wrapper) — GeoNames, CC-BY 4.0
 *   world-countries 5.1.0 (ODbL) — curated country metadata
 *
 * GeoNames attribution is mandatory and lives on the page and on cards:
 * "Place data © GeoNames (CC BY 4.0)".
 */
'use strict';

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'maps', 'data');
const GAZETTEER = path.join(DATA, 'gazetteer.json');
const COUNTRY_FACTS = path.join(DATA, 'countries.json');
const SOURCES = path.join(DATA, 'SOURCES.json');

// Cities at or above this population are kept, plus every national capital
// (feature code PPLC) however small. 20,000 was chosen by size: it is ~19.6k
// rows and ~0.9 MB of JSON, ~250 KB over the wire, which is a fair price for
// search that works on a plane. Lower thresholds double the file for places
// nobody searches for.
const MIN_POPULATION = 20000;
const COORD_DECIMALS = 4; // ~11 m: finer than any gazetteer row is accurate

const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : null;
};
const CHECK = args.includes('--check');

const die = (msg) => {
  process.stderr.write(`build-maps-data: ${msg}\n`);
  process.exit(1);
};

const sha256 = (buf) => crypto.createHash('sha256').update(buf).digest('hex');
const round = (n, d) => Number(n.toFixed(d));

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

// ---------------------------------------------------------------- generation

function buildGazetteer(citiesPbf, nodePath) {
  // all-the-cities ships a protobuf and a tiny reader that requires `pbf`.
  // We read the same protobuf with the same reader rather than re-deriving it.
  if (nodePath) module.paths.push(nodePath);
  const { spawnSync } = require('child_process');
  const pbfPath = path.join(path.dirname(citiesPbf), 'index.js');
  if (!fs.existsSync(pbfPath)) {
    die(`expected the all-the-cities reader next to the protobuf: ${pbfPath}`);
  }
  // Decode in a child process so --require/pbf resolution does not leak here.
  const reader = `
    const cities = require(${JSON.stringify(pbfPath)});
    const rows = cities
      .filter(c => c.population >= ${MIN_POPULATION} || c.featureCode === 'PPLC')
      .map(c => [c.name, Number(c.loc.coordinates[1].toFixed(${COORD_DECIMALS})),
                  Number(c.loc.coordinates[0].toFixed(${COORD_DECIMALS})),
                  c.country, c.population]);
    rows.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : (a[3] < b[3] ? -1 : 1)));
    process.stdout.write(JSON.stringify(rows));
  `;
  const res = spawnSync(process.execPath, ['-e', reader], {
    env: { ...process.env, NODE_PATH: nodePath || process.env.NODE_PATH || '' },
    maxBuffer: 512 * 1024 * 1024,
  });
  if (res.status !== 0) {
    die(`decoding cities.pbf failed:\n${res.stderr}`);
  }
  const rows = JSON.parse(res.stdout.toString());
  return {
    v: 1,
    note:
      'Offline gazetteer for MostUsefulMaps. Generated by scripts/build-maps-data.js — do not hand-edit.',
    source: 'all-the-cities@3.1.0 (GeoNames) — CC BY 4.0',
    min_population: MIN_POPULATION,
    // [name, lat, lon, countryCode, population]
    fields: ['name', 'lat', 'lon', 'cc', 'pop'],
    cities: rows,
  };
}

function buildCountryFacts(countriesJson) {
  const out = {};
  for (const c of countriesJson) {
    const name = c.name && c.name.common;
    if (!name || !c.cca2) continue;
    out[c.cca2] = {
      name,
      official: (c.name.official || name).slice(0, 200),
      n3: c.ccn3 || null, // joins to world-atlas' numeric geometry ids
      cca3: c.cca3 || null,
      capital: Array.isArray(c.capital) && c.capital.length ? c.capital[0] : null,
      region: c.region || null,
      subregion: c.subregion || null,
      latlng: Array.isArray(c.latlng) ? [round(c.latlng[0], 4), round(c.latlng[1], 4)] : null,
      area: typeof c.area === 'number' ? c.area : null,
      landlocked: !!c.landlocked,
      unMember: !!c.unMember,
      flag: c.flag || null,
      currencies: Object.entries(c.currencies || {})
        .map(([code, cur]) => `${cur.name} (${cur.symbol || code})`)
        .slice(0, 4),
      languages: Object.values(c.languages || {}).slice(0, 8),
      calling: c.idd && c.idd.root ? c.idd.root + ((c.idd.suffixes || [])[0] || '') : null,
      tld: Array.isArray(c.tld) && c.tld.length ? c.tld[0] : null,
      borders: Array.isArray(c.borders) ? c.borders.slice(0, 20) : [],
    };
  }
  return {
    v: 1,
    note:
      'Offline country facts for MostUsefulMaps. Generated by scripts/build-maps-data.js — do not hand-edit.',
    source: 'world-countries@5.1.0 — ODbL',
    fields: [
      'name', 'official', 'n3', 'cca3', 'capital', 'region', 'subregion', 'latlng',
      'area', 'landlocked', 'unMember', 'flag', 'currencies', 'languages', 'calling',
      'tld', 'borders',
    ],
    countries: out,
  };
}

// --------------------------------------------------------------------- check

function cmdCheck() {
  if (!fs.existsSync(SOURCES)) {
    die('maps/data/SOURCES.json is missing — run the generator with sources once');
  }
  const sources = readJson(SOURCES);
  let bad = 0;
  for (const entry of sources.outputs) {
    const file = path.join(ROOT, entry.file);
    if (!fs.existsSync(file)) {
      process.stderr.write(`MISSING  ${entry.file}\n`);
      bad += 1;
      continue;
    }
    const buf = fs.readFileSync(file);
    const hash = sha256(buf);
    if (hash !== entry.sha256) {
      process.stderr.write(
        `DRIFT    ${entry.file}\n         committed ${hash}\n         recorded  ${entry.sha256}\n` +
        `         regenerate: node scripts/build-maps-data.js --cities … --countries …\n`
      );
      bad += 1;
      continue;
    }
    const parsed = JSON.parse(buf.toString('utf8'));
    const rows = parsed.cities ? parsed.cities.length : Object.keys(parsed.countries || {}).length;
    if (rows !== entry.rows) {
      process.stderr.write(`DRIFT    ${entry.file}: ${rows} rows, expected ${entry.rows}\n`);
      bad += 1;
    }
  }
  if (bad) process.exit(1);
  process.stdout.write(
    `maps data OK — ${sources.outputs.length} generated files match their recorded hashes\n`
  );
}

